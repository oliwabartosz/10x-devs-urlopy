/**
 * Finish the deployable artifact after `astro build`.
 *
 * `astro build` produces `dist/server/entry.mjs` and `dist/client/` — enough to serve requests, but
 * not enough to *provision* a machine. The VPS is offline and installs with `--omit=dev`, so it has
 * neither `tsx` nor `drizzle-kit`; migrating and seeding there needs plain JavaScript plus the
 * migration SQL. This script supplies both, so everything `install.sh` needs lives under `dist/`
 * and the archive stays `dist/ + node_modules/ + package.json + deploy/`.
 *
 * Runs automatically as npm's `postbuild` hook.
 *
 * Outputs:
 *   dist/bootstrap.mjs    bundled migrate + seed entry (see scripts/bootstrap.ts)
 *   dist/drizzle/         the generated migrations, copied verbatim
 *   dist/build-info.json  what this build was built for — install.sh warns on an origin mismatch
 */
import { build } from "esbuild";
import { loadEnv } from "vite";
import { cp, rm, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const dist = `${root}dist`;

await mkdir(dist, { recursive: true });

await build({
  entryPoints: [`${root}scripts/bootstrap.ts`],
  outfile: `${dist}/bootstrap.mjs`,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node24",
  // Leave every npm import as a runtime `import` — `node_modules/` ships alongside `dist/`, so
  // inlining drizzle-orm would only duplicate what is already on the box. It also keeps this
  // bundle small enough to read, which matters for a script that runs as root's first act on a
  // machine nobody can SSH into a second time.
  packages: "external",
  // `scripts/seed-admin.ts` ends in an `if (import.meta.main)` CLI block. In a bundle, `import.meta
  // .main` is the *entry* module's value — true here — so that block would fire and call
  // `process.loadEnvFile()`, which throws on a VPS with no `.env`. Folding it to `false` drops the
  // branch entirely; `scripts/bootstrap.ts` calls the exported `seedAdmin` directly instead.
  define: { "import.meta.main": "false" },
  banner: {
    js: "// Generated by scripts/build-artifact.mjs — do not edit. Source: scripts/bootstrap.ts",
  },
});

await rm(`${dist}/drizzle`, { recursive: true, force: true });
await cp(`${root}drizzle`, `${dist}/drizzle`, { recursive: true });

// Resolved exactly the way astro.config.mjs resolves it — `process.env` first, then `.env` via
// vite's loader. Reading only `process.env` here would report "unset" for a build that in fact
// baked in the origin from `.env`, and install.sh would then warn about a problem that is not
// there while missing the mismatch it exists to catch.
const viteEnv = loadEnv(process.env.NODE_ENV ?? "production", process.cwd(), "");
// Split rather than chained with `||` for the same reason astro.config.mjs splits it: `loadEnv`
// returns a plain string record, so an unset key is `""`, never nullish, and `??` would happily
// hand on the empty string.
const configuredOrigin = process.env.PUBLIC_ORIGIN ?? viteEnv.PUBLIC_ORIGIN;
const publicOrigin = configuredOrigin ? configuredOrigin : null;
await writeFile(
  `${dist}/build-info.json`,
  `${JSON.stringify(
    {
      // The origin baked into `site` and `security.allowedDomains` by astro.config.mjs. `install.sh`
      // compares it against its own `--origin` and refuses to continue on a mismatch, because the
      // symptom otherwise is a 403 on sign-in only — every JSON route keeps working, so it reads
      // as a password problem rather than a build problem.
      publicOrigin,
      node: process.version,
      builtAt: new Date().toISOString(),
    },
    null,
    2,
  )}\n`,
);

console.log(
  `✔ artifact ready: dist/bootstrap.mjs, dist/drizzle/, dist/build-info.json (origin: ${publicOrigin ?? "unset"})`,
);
